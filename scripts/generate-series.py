def main():
    groups = {}
    for p in glob.glob(os.path.join(BOOKS_DIR, "*.md")):
        d = fm(p)
        s = d.get("series")
        if not s:
            continue
        groups.setdefault(s, []).append(d)

    # remove stale generated pages
    for p in glob.glob(os.path.join(SERIES_DIR, "*", "index.html")):
        if MARKER in open(p, encoding="utf-8").read():
            os.remove(p)

    made = []
    for name in sorted(groups):
        books = groups[name]
        if len(books) <= 1:
            continue
        en = next((b.get("series_en") for b in sorted(
            books, key=lambda b: int(b.get("series_order") or 999)) if b.get("series_en")), "")
        slug = slugify(en) if en else slugify(name)
        assert slug, name
        bn, en_desc = DESC.get(name, (
            "এই সিরিজের %dটি বই একসাথে সংগৃহীত রয়েছে — অনলাইনে পড়ুন বা ফ্রি ডাউনলোড করুন।" % len(books),
            "%d books of this series collected together — read online or download free." % len(books)))
        outdir = os.path.join(SERIES_DIR, slug)
        os.makedirs(outdir, exist_ok=True)
        out = os.path.join(outdir, "index.html")
        open(out, "w", encoding="utf-8").write(PAGE_TEMPLATE.format(
            title=q(name + " — সিরিজ"), slug=slug, name=q(name),
            desc_bn=q(bn), desc_en=q(en_desc), marker=MARKER))
        made.append((slug, name, len(books)))
    for slug, name, n in made:
        print(f"{slug}  ({n})  {name}")
    print(f"total: {len(made)} series pages")


if __name__ == "__main__":
    main()
