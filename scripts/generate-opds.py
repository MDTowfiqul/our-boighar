#!/usr/bin/env python3
"""Generate the OPDS feed files for Our Boighar (xKAF Phase 2).

Reads every book in _books/, and writes thin Jekyll wrappers under opds/:

  opds/all-N.xml          All books, A-Z, 50 per page (N pages for the
                          current book count; re-run if books pass 500)
  opds/category-<slug>.xml  One acquisition feed per category (18)
  opds/author-<slug>.xml    One acquisition feed per top-20 author
  opds/authors.xml          Navigation feed listing the top-20 authors

Each generated file is a small Liquid template: the book entries themselves
are rendered at Jekyll build time by _includes/opds-feed.xml /
_includes/opds-entry.xml, so a feed stays current when books are added or
removed. Only the *set* of files goes stale -- re-run this script after
adding a book in a brand-new category, or when the top-20 authors change:

    python3 scripts/generate-opds.py

Hand-written OPDS files (not touched by this script): opds/catalog.xml,
opds/categories.xml, opds/new.xml, opds/popular.xml, opds/index.html.

Generated files carry a marker comment in their front matter; re-running
deletes stale generated files that carry the marker.
"""

import collections
import glob
import math
import os
import re
import sys
import xml.sax.saxutils as sax

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOOKS_DIR = os.path.join(ROOT, "_books")
SLUGS_FILE = os.path.join(ROOT, "_data", "author_slugs.yml")
OPDS_DIR = os.path.join(ROOT, "opds")
MARKER = "# generated by scripts/generate-opds.py - do not edit by hand"
PAGE_SIZE = 50
TOP_AUTHORS = 20


def slugify(text):
    """Jekyll `slugify` (default mode) for ASCII names: lowercase, every run
    of non-alphanumeric characters becomes one dash, no leading/trailing
    dash. (Only used for category names, which are all ASCII.)"""
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower())
    return slug.strip("-")


def front_matter(path):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError(f"no front matter in {path}")
    return yaml.safe_load(m.group(1))


def write(path, body):
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(body)
    print(f"  wrote {os.path.relpath(path, ROOT)}")


def all_pages(n_books):
    return max(1, math.ceil(n_books / PAGE_SIZE))


def main():
    books = []
    for path in sorted(glob.glob(os.path.join(BOOKS_DIR, "*.md"))):
        fm = front_matter(path)
        books.append(fm)
    print(f"{len(books)} books")

    with open(SLUGS_FILE, encoding="utf-8") as fh:
        author_slugs = yaml.safe_load(fh) or {}

    categories = collections.Counter()
    authors = collections.Counter()
    for b in books:
        # Site browse semantics (browse.html): a book belongs to every
        # category in its `categories` list, so a book can appear in more
        # than one category feed. Fall back to the primary `category` when
        # the list is absent.
        for c in b.get("categories") or [b["category"]]:
            categories[c] += 1
        authors[b["author"]] += 1
    print(f"{len(categories)} categories, {len(authors)} authors")

    top_authors = sorted(authors.items(), key=lambda kv: (-kv[1], kv[0]))[:TOP_AUTHORS]
    missing_slugs = [a for a, _ in top_authors if a not in author_slugs]
    if missing_slugs:
        print("ERROR: top authors with no slug in _data/author_slugs.yml "
              "(run scripts/generate-authors.py first):")
        for a in missing_slugs:
            print(f"  {a}")
        sys.exit(1)

    os.makedirs(OPDS_DIR, exist_ok=True)

    # --- delete stale generated files -------------------------------------
    for path in glob.glob(os.path.join(OPDS_DIR, "*.xml")):
        with open(path, encoding="utf-8", errors="ignore") as fh:
            head = fh.read(500)
        if MARKER in head:
            os.remove(path)
            print(f"  removed stale {os.path.relpath(path, ROOT)}")

    # --- opds/all-N.xml ----------------------------------------------------
    n_pages = all_pages(len(books))
    for n in range(1, n_pages + 1):
        offset = (n - 1) * PAGE_SIZE
        params = [
            f'feed_title="Our Boighar — All Books (page {n} of {n_pages})"',
            f'self_href="/opds/all-{n}.xml"',
            'kind="acquisition"',
            "books=books",
            f"page_size={PAGE_SIZE}",
            f"page_offset={offset}",
            f'first_href="/opds/all-1.xml"',
        ]
        if n > 1:
            params.append(f'prev_href="/opds/all-{n - 1}.xml"')
        if n < n_pages:
            params.append(f'next_href="/opds/all-{n + 1}.xml"')
        params.append(f'last_href="/opds/all-{n_pages}.xml"')
        write(
            os.path.join(OPDS_DIR, f"all-{n}.xml"),
            "---\nlayout: null\n" + MARKER + "\n---\n"
            "{%- assign books = site.books | sort: \"title\" -%}\n"
            "{%- include opds-feed.xml " + " ".join(params) + " -%}\n",
        )

    # --- opds/category-<slug>.xml ------------------------------------------
    # where_exp on the `categories` list (same semantics as browse.html):
    # a book with two categories appears in both feeds.
    for cat in sorted(categories):
        if '"' in cat:
            print(f"ERROR: category name contains a double quote: {cat}")
            sys.exit(1)
        slug = slugify(cat)
        write(
            os.path.join(OPDS_DIR, f"category-{slug}.xml"),
            "---\nlayout: null\n" + MARKER + "\n---\n"
            "{%- assign _cat = \"" + cat + "\" -%}\n"
            "{%- assign books = site.books | where_exp: \"b\", \"b.categories contains _cat\" | sort: \"title\" -%}\n"
            "{%- include opds-feed.xml "
            'feed_title="Our Boighar — ' + cat + '" '
            'self_href="/opds/category-' + slug + '.xml" kind="acquisition" books=books -%}\n',
        )

    # --- opds/author-<slug>.xml + opds/authors.xml --------------------------
    author_entries = []
    for author, count in top_authors:
        if '"' in author:
            print(f"ERROR: author name contains a double quote: {author}")
            sys.exit(1)
        slug = author_slugs[author]
        write(
            os.path.join(OPDS_DIR, f"author-{slug}.xml"),
            "---\nlayout: null\n" + MARKER + "\n---\n"
            "{%- assign books = site.books | where: \"author\", \"" + author + "\" | sort: \"title\" -%}\n"
            "{%- include opds-feed.xml "
            'feed_title="Our Boighar — Books by ' + author + '" '
            'self_href="/opds/author-' + slug + '.xml" kind="acquisition" books=books -%}\n',
        )
        author_entries.append((author, count, slug))

    lines = [
        "---",
        "layout: null",
        MARKER,
        "---",
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<feed xmlns="http://www.w3.org/2005/Atom" xmlns:dc="http://purl.org/dc/terms/" xmlns:opds="http://opds-spec.org/2010/catalog">',
        "  <id>{{ '/opds/authors.xml' | absolute_url }}</id>",
        "  <title>Our Boighar — Authors</title>",
        "  <updated>{{ site.time | date_to_xmlschema }}</updated>",
        "  <author><name>Our Boighar</name><uri>{{ '/' | absolute_url }}</uri></author>",
        '  <link rel="self" type="application/atom+xml;profile=opds-catalog;kind=navigation" href="{{ \'/opds/authors.xml\' | absolute_url }}"/>',
        '  <link rel="start" type="application/atom+xml;profile=opds-catalog;kind=navigation" title="Our Boighar OPDS Catalog" href="{{ \'/opds/catalog.xml\' | absolute_url }}"/>',
    ]
    for author, count, slug in author_entries:
        href = "/opds/author-" + slug + ".xml"
        lines.append("  <entry>")
        lines.append(f"    <title>{sax.escape(author)} ({count})</title>")
        lines.append("    <id>{{ '" + href + "' | absolute_url }}</id>")
        lines.append("    <updated>{{ site.time | date_to_xmlschema }}</updated>")
        lines.append(f"    <content type=\"text\">{count} book(s) by {sax.escape(author)}.</content>")
        lines.append(
            '    <link rel="subsection" type="application/atom+xml;profile=opds-catalog;kind=acquisition" href="{{ \''
            + href
            + "' | absolute_url }}\"/>"
        )
        lines.append("  </entry>")
    lines.append("</feed>")
    lines.append("")
    write(os.path.join(OPDS_DIR, "authors.xml"), "\n".join(lines))

    print(
        f"done: {n_pages} all-books pages, {len(categories)} category feeds, "
        f"{len(author_entries)} author feeds + authors index"
    )


if __name__ == "__main__":
    main()
