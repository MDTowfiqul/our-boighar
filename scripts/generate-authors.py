def slugify(name):
    s = name.strip().lower()
    # keep latin letters/digits and Bengali range; everything else -> dash
    s = re.sub(r"[^a-z0-9\u0980-\u09ff]+", "-", s)
    s = s.strip("-")
    return s or "author"


def read_author(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.search(r"^---\s*\n(.*?)\n---", text, re.S)
    if not m:
        return None
    fm = m.group(1)
    am = re.search(r"^author:\s*(.+?)\s*$", fm, re.M)
    if not am:
        return None
    val = am.group(1).strip()
    if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
        val = val[1:-1]
    return val.strip()


def main():
    authors = set()
    for path in glob.glob(os.path.join(BOOKS_DIR, "*.md")):
        a = read_author(path)
        if a:
            authors.add(a)
    if not authors:
        print("no authors found", file=sys.stderr)
        return 1

    # deterministic order so collision suffixes are stable
    ordered = sorted(authors, key=lambda s: s.lower())
    used = {}
    mapping = {}
    for name in ordered:
        base = slugify(name)
        slug = base
        n = 2
        while slug in used:
            slug = "%s-%d" % (base, n)
            n += 1
        used[slug] = name
        mapping[name] = slug

    os.makedirs(os.path.dirname(DATA_FILE), exist_ok=True)
    with open(DATA_FILE, "w", encoding="utf-8") as f:
        f.write("# author name -> URL slug under /authors/<slug>/\n")
        f.write("# Generated by scripts/generate-authors.py - do not edit by hand.\n")
        for name in ordered:
            f.write("%s: %s\n" % (json.dumps(name, ensure_ascii=False),
                                  json.dumps(mapping[name], ensure_ascii=False)))

    # remove stale generated pages
    if os.path.isdir(AUTHORS_DIR):
        for root, _dirs, files in os.walk(AUTHORS_DIR):
            for fn in files:
                p = os.path.join(root, fn)
                try:
                    with open(p, encoding="utf-8") as f:
                        head = f.read(4096)
                except OSError:
                    continue
                if MARKER in head and os.path.relpath(p, AUTHORS_DIR) not in (
                    os.path.join(mapping[n], "index.html") for n in ordered
                ):
                    os.remove(p)

    for name in ordered:
        slug = mapping[name]
        d = os.path.join(AUTHORS_DIR, slug)
        os.makedirs(d, exist_ok=True)
        title = "%s — লেখক" % name
        content = PAGE_TEMPLATE.format(
            title=json.dumps(title, ensure_ascii=False)[1:-1],
            slug=slug,
            author_json=json.dumps(name, ensure_ascii=False),
            marker=MARKER,
        )
        with open(os.path.join(d, "index.html"), "w", encoding="utf-8") as f:
            f.write(content)

    print("authors: %d, pages written to %s" % (len(authors), AUTHORS_DIR))
    print("slug map written to %s" % DATA_FILE)
    return 0


if __name__ == "__main__":
    sys.exit(main())
