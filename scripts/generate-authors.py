#!/usr/bin/env python3
"""Generate one static page per author for Our Boighar (xKAF Phase 1).

Reads every book in _books/, builds a slug for each distinct author name
(same spelling variants stay separate pages; exact slug collisions get a
-2, -3 suffix), writes the author -> slug map to _data/author_slugs.yml,
and writes one page per author under authors/<slug>/index.html.

The generated pages are thin Jekyll wrappers: the book list on each page is
rendered at build time with Liquid (`site.books | where: "author", ...`),
so a page stays current when books by that author are added or removed.
Only the slug map goes stale for a brand-new author name -- re-run this
script after adding a book by an author who has no page yet:

    python3 scripts/generate-authors.py

Generated files carry a marker comment; re-running deletes stale pages
that carry the marker and regenerates everything.
"""
