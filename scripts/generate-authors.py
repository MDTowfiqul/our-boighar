BOOKS_DIR = os.path.join(ROOT, "_books")
DATA_FILE = os.path.join(ROOT, "_data", "author_slugs.yml")
AUTHORS_DIR = os.path.join(ROOT, "authors")
MARKER = "<!-- generated by scripts/generate-authors.py - do not edit by hand -->"

